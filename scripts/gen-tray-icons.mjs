// Generates src-tauri/src/tray_icons.rs from src/views/icon-catalog.json: each symbol's
// lucide IconNode becomes SVG markup the tray rasterizer renders. Run after editing the
// catalog:  node scripts/gen-tray-icons.mjs
import { readFile, writeFile } from "node:fs/promises";
import * as lucide from "lucide";

const CATALOG_URL = new URL("../src/views/icon-catalog.json", import.meta.url);
const OUT_URL = new URL("../src-tauri/src/tray_icons.rs", import.meta.url);

const { symbols } = JSON.parse(await readFile(CATALOG_URL, "utf8"));

const svgFor = (name) => {
  const node = lucide[name];
  if (!node) throw new Error(`lucide has no icon named ${name}`);
  const body = node.map(element).join("");
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" ` +
    `fill="none" stroke="#555555" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">` +
    `${body}</svg>`
  );
};

// A lucide IconNode element is [tag, attrs, children]; React's `key` is not SVG.
const element = ([tag, attrs, children]) => {
  const rest = Object.fromEntries(
    Object.entries(attrs ?? {}).filter(([name]) => name !== "key"),
  );
  const a = Object.entries(rest)
    .map(([name, value]) => ` ${name}="${value}"`)
    .join("");
  const kids = (children ?? []).map(element).join("");
  return kids ? `<${tag}${a}>${kids}</${tag}>` : `<${tag}${a}/>`;
};

// JSON.stringify escapes quotes exactly like a Rust string literal, and the SVG never
// contains a backslash, so the emitted literal is always valid Rust.
const rustLit = (svg) => JSON.stringify(svg);

const arms = symbols
  .map(({ name }) => `        "${name}" => Some(${rustLit(svgFor(name))}),\n`)
  .join("");

const file = `// GENERATED by scripts/gen-tray-icons.mjs — do not edit by hand.
// Lucide icon SVG markup for the tray's group headers. Covers every name in
// src/views/icon-catalog.json; unknown names render the default group glyph.

pub const DEFAULT_SVG: &str = ${rustLit(svgFor("FolderTree"))};

pub fn svg(name: &str) -> Option<&'static str> {
    match name {
${arms}        _ => None,
    }
}
`;

await writeFile(OUT_URL, file);
console.log(`wrote ${OUT_URL.pathname.split("/").at(-1)} (${symbols.length} icons)`);
